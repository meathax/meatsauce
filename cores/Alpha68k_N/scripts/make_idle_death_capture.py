"""Derive a finite real-game death/game-over oracle from the canonical recorder."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = ROOT / "sim/mame/capture.lua"
    text = source.read_text()
    substitutions = [
        ('local total = tonumber(os.getenv("ALPHA_CAPTURE_FRAMES") or "1800")',
         'if mode == "idle-death" then\n'
         '    local dip_port = assert(machine.ioport.ports["IN1"] or machine.ioport.ports[":IN1"], "DIP port missing")\n'
         '    local difficulty = assert(dip_port.fields["Difficulty"], "difficulty DIP missing")\n'
         '    difficulty.user_value = 0x40 -- legal hard DIP; default three lives\n'
         'end\nlocal total = tonumber(os.getenv("ALPHA_CAPTURE_FRAMES") or "1800")'),
        ('if mode ~= "gameplay" then return end',
         'if mode ~= "gameplay" and mode ~= "idle-death" then return end'),
        ('if frame == 166 then set_input("IN0",0x80,false) end',
         'if frame == 166 then set_input("IN0",0x80,false) end\n'
         '    if mode == "idle-death" then return end -- enemies drive death naturally'),
        ('if sample_frames[frame] or frame == total-1 then snapshot() end',
         'if sample_frames[frame] or (mode == "idle-death" and frame >= 720 and frame % 240 == 0) or frame == total-1 then snapshot() end'),
        ('if frame < 260 or (frame >= 590 and frame < 610) or (frame >= 1190 and frame < 1210) then',
         'if true then -- retain complete sound observations for the finite scenario'),
    ]
    for old, new in substitutions:
        if text.count(old) != 1:
            raise ValueError("canonical recorder changed: " + old)
        text = text.replace(old, new, 1)
    target = ROOT / "sim/mame/capture_idle_death.lua"
    target.write_text("-- Generated by scripts/make_idle_death_capture.py; CPU/RAM execution is unchanged.\n" + text, newline="\n")
    result = {"canonical_source": str(source.relative_to(ROOT)),
              "canonical_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
              "derived_source": str(target.relative_to(ROOT)),
              "derived_sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
              "scenario": "idle-death", "inputs": "coin120..125, start160..165, then no movement/buttons",
              "dip": "IN1 Difficulty=0x40; three lives; actual hardware DIP setting",
              "observations": "240-field snapshots from720; complete sound writes",
              "scope": "real MAME CPUs; no RAM/register patches or forced game transitions"}
    (ROOT / "research/kyros_idle_death_source.json").write_text(json.dumps(result, indent=2) + "\n", newline="\n")
    print(json.dumps(result))


if __name__ == "__main__":
    main()
