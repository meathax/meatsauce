"""Use the same target audio source closure in Quartus and Verilator; no build."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
paths=[root/line.strip() for line in (root/'sim/audio_sources.f').read_text().splitlines() if line.strip()]
assert paths and len(paths)==len(set(paths))
lines=['# Generated by scripts/stage_platform_audio.py from the tested audio closure.']
for path in paths:
    assert path.is_file(),path
    relative=path.relative_to(root/'rtl').as_posix()
    kind='SYSTEMVERILOG_FILE' if path.suffix=='.sv' else 'VERILOG_FILE'
    assert path.suffix in ('.sv','.v'),path
    lines.append(f'set_global_assignment -name {kind} [file join $::quartus(qip_path) "{relative}"]')
for directory in ('sound/jtopl','sound/jt6295'):
    lines.append(f'set_global_assignment -name SEARCH_PATH [file join $::quartus(qip_path) "{directory}"]')
(root/'rtl/ZeroTeam_audio.qip').write_text('\n'.join(lines)+'\n')
wrapper=root/'ZeroTeam.sv'
text=wrapper.read_text()
if 'Raiden2_audio_z80 #(' in text:
    begin=text.index('// ── Audio Seibu reale:')
    end=text.index('// ── Isolatore OSD',begin)
    replacement='''// Target sound: the same real TV80/OPL2/single OKI used by zero_av_top.
// The donor download layout still needs final loader/MRA adaptation.
wire [17:0] target_oki_addr;
assign oki_rom_addr={1'b0,target_oki_addr};
assign oki2_rom_addr=19'd0;
assign z80_ss_ready=1'b1;
ZeroTeam_audio u_audio (
    .clk(clk_sys),.reset(reset),.pause(paused_safe),
    .ioctl_download(ioctl_download),.ioctl_wr(ioctl_wr),
    .ioctl_addr(ioctl_addr),.ioctl_dout(ioctl_dout),
    .snd_cs(snd_cs),.snd_addr(snd_addr[3:1]),.snd_wr(snd_wr),.snd_rd(snd_rd),
    .snd_wdata(snd_wdata),.snd_rdata(snd_rdata),.coin_input(coin_input),
    .oki_rom_addr(target_oki_addr),.oki_rom_data(oki_rom_data),.oki_rom_ok(oki_rom_ok),
    .audio_l(game_audio_l),.audio_r(game_audio_r),.audio_sample(),
    .debug_address(),.debug_data(),.debug_din(),.debug_read(),.debug_write(),
    .debug_fetch(),.debug_iack(),.debug_cen(),.debug_ym_irq(),.debug_pending()
);
// These legacy slots have no target sound savestate owner.
ss_null_slave #(.SS_IDX(10)) u_no_audio_ram (.clk(clk_sys),.ssbus(ssb[10]));
ss_null_slave #(.SS_IDX(12)) u_no_audio_cpu (.clk(clk_sys),.ssbus(ssb[12]));
ss_null_slave #(.SS_IDX(13)) u_no_audio_fm (.clk(clk_sys),.ssbus(ssb[13]));
ss_null_slave #(.SS_IDX(14)) u_no_audio_glue (.clk(clk_sys),.ssbus(ssb[14]));

'''
    wrapper.write_text(text[:begin]+replacement+text[end:])
print(f'Staged {len(paths)} target audio sources; no Quartus/RBF build performed.')
