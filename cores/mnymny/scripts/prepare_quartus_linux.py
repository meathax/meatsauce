"""Generate an isolated Windows Quartus project; never invoke a compiler.

Run in Ubuntu WSL. All native Quartus work must subsequently use the global
MCP queue. The snapshot is retained for the queued job and its reports.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from datetime import date

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--snapshot', required=True, type=Path)
parser.add_argument('--resume-generation', action='store_true')
parser.add_argument('--jtframe', required=True, type=Path)
args = parser.parse_args()
snapshot = args.snapshot.resolve()
assert str(snapshot).startswith('/mnt/d/vibes/fpga/temp/mnymny-')
# Current donor inputs are already prepared and stored alongside these sources.
assert (ROOT/'donors/jtcores/modules/jtframe').is_dir()
if args.resume_generation:
    prior = json.loads((snapshot/'source-manifest.json').read_text())
    for name, expected in prior.items():
        # A failed generator may have left partial outputs. They are rebuilt
        # from the pinned source tree below, never admitted as source inputs.
        if name.startswith('project/'):
            continue
        assert hashlib.sha256((snapshot/name).read_bytes()).hexdigest() == expected, name
else:
    assert not snapshot.exists(), 'Never overwrite an existing project or job'
    for adaptation in ('apply_platform.py','apply_rotation.py'):
        command = [sys.executable,str(ROOT/'scripts'/adaptation)]
        if adaptation=='apply_rotation.py':
            command.append('--install')
        subprocess.run(command,cwd=ROOT,check=True)
    snapshot.mkdir(parents=True)
    subprocess.run(['git', 'init', '--quiet', str(snapshot)], check=True)
    source_commit = subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip()
    (snapshot/'.git/HEAD').write_text(source_commit+'\n')
donor = ROOT / 'donors/jtcores'
if not args.resume_generation:
    for name in ('modules', 'doc'):
        shutil.copytree(donor / name, snapshot / name)
    shutil.copytree(ROOT / 'cores/mnymny', snapshot / 'cores/mnymny',
                    ignore=shutil.ignore_patterns('ver', '__pycache__'))
    shutil.copytree(ROOT / 'framework', snapshot / 'framework')
subprocess.run([sys.executable, str(ROOT/'scripts/apply_credits.py'),
                '--snapshot', str(snapshot)], cwd=ROOT, check=True)
work = snapshot / 'project'
work.mkdir(exist_ok=args.resume_generation)
env = dict(os.environ, JTROOT=str(snapshot), JTFRAME=str(snapshot/'modules/jtframe'),
           MODULES=str(snapshot/'modules'), CORES=str(snapshot/'cores'),
           ROM=str(snapshot/'rom'), RLS=str(snapshot/'release'),
           MRA=str(snapshot/'release/mra'), JTBIN=str(snapshot/'jtbin'))
tool_path = args.jtframe
with tool_path.open('rb') as tool_file:
    if tool_file.read(4) != b'\x7fELF':
        raise RuntimeError('JTFRAME tool must be a Linux ELF; build it with scripts/build_jtframe_linux.py')
tool = str(tool_path)
receipts = []

def run(arguments, output=None):
    result = subprocess.run([tool, *arguments], cwd=work, env=env,
                            capture_output=True, text=True)
    receipts.append(dict(arguments=arguments, exit_code=result.returncode,
                         stdout=result.stdout, stderr=result.stderr))
    (work/'generation.json').write_text(json.dumps(receipts, indent=2)+'\n')
    result.check_returncode()
    if output:
        (work/output).write_text(result.stdout)

run(['mem', 'mnymny', '--target=mister', '--local'])
run(['mmr', 'mnymny'])
run(['files', 'syn', 'mnymny', '--target=mister', '--local'])
for suffix in ('qpf', 'qsf'):
    run(['parse', 'mnymny', str(snapshot/f'modules/jtframe/target/mister/mister.{suffix}'),
         '--target=mister', '--output', str(work/f'jtmnymny.{suffix}')])
qpf = work/'jtmnymny.qpf'
qpf.write_text(qpf.read_text().replace('${CORENAME}', 'mnymny')
               .replace('${DATE}', date.today().isoformat()))
run(['cfgstr', 'mnymny', '--target=mister', '--output=quartus'], 'macros.qsf')
run(['cfgstr', 'mnymny', '--target=mister', '--output=cfgstr'], 'cfgstr.txt')
assert (work/'cfgstr.hex').is_file(), 'HPS consumes the generated byte ROM'
cfg_bytes = bytes(int(token,16) for token in (work/'cfgstr.hex').read_text().split())
cfg_string = cfg_bytes.split(b'\0',1)[0].decode('ascii')
assert 'Rotate screen,CW,Original,180,CCW;' in cfg_string
(work/'cfgstr.txt').write_text(cfg_string+'\n')
qsf = work/'jtmnymny.qsf'
with qsf.open('a') as out:
    out.write('\n'+(work/'macros.qsf').read_text())
    out.write('\nset_global_assignment -name SEARCH_PATH "'+str(snapshot/'cores/mnymny/hdl')+'"\n')
    # These apply to the future authorized release too; analysis alone cannot
    # produce an RBF or establish compression/timing qualification.
    out.write('set_global_assignment -name COMPRESSION_MODE ON\n')
    out.write('set_global_assignment -name ON_CHIP_BITSTREAM_DECOMPRESSION ON\n')
    out.write('set_global_assignment -name TIMEQUEST_MULTICORNER_ANALYSIS ON\n')
    out.write('set_global_assignment -name NUM_PARALLEL_PROCESSORS 8\n')
    out.write('set_global_assignment -name QIP_FILE "'+str(snapshot/'cores/mnymny/credits/credits.qip')+'"\n')
# Replace the stock build-id-only preflow with a chained hook that also
# regenerates the embedded credits ROM (and still runs the stock build-id hook).
qsf_text = qsf.read_text()
preflow_lines = [line for line in qsf_text.splitlines()
                 if 'set_global_assignment -name PRE_FLOW_SCRIPT_FILE ' in line]
assert len(preflow_lines) == 1, 'Unexpected original Quartus preflow hook'
qsf.write_text(qsf_text.replace(preflow_lines[0],
    'set_global_assignment -name PRE_FLOW_SCRIPT_FILE "quartus_sh:'+str(snapshot/'cores/mnymny/credits/host_preflow.tcl')+'"'))
for directory in (snapshot/'cores/mnymny/hdl', snapshot/'modules/jtframe/hdl/sound',
                  snapshot/'modules/jtframe/hdl/video', snapshot/'modules/jtframe/bin'):
    for item in directory.glob('*.hex'):
        target = work/item.name
        if target.exists():
            assert target.read_bytes() == item.read_bytes(), item
        else:
            shutil.copy2(item, target)
# Go emits absolute POSIX paths. Translate generated project text only; HDL,
# SDC and the pinned device sources retain their exact bytes.
for p in work.iterdir():
    if p.suffix in ('.qip', '.qsf', '.qpf'):
        p.write_text(p.read_text().replace('/mnt/d/', 'D:/').replace('/mnt/c/', 'C:/'))
manifest = {}
for parent in (snapshot/'cores', snapshot/'modules'):
    for p in sorted(parent.rglob('*')):
        if p.is_file():
            manifest[str(p.relative_to(snapshot))] = hashlib.sha256(p.read_bytes()).hexdigest()
for p in sorted(work.iterdir()):
    if p.is_file() and p.suffix in ('.qip','.qsf','.qpf','.hex','.v','.vh','.uc','.inc','.txt'):
        manifest[str(p.relative_to(snapshot))] = hashlib.sha256(p.read_bytes()).hexdigest()
(snapshot/'source-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
print(json.dumps(dict(project=str(qsf).replace('/mnt/d/', 'D:/'),
                     files=len(manifest), compiler_invoked=False)))
