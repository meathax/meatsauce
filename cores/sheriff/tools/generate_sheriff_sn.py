"""Generate fixed point Sheriff SN76477 constants from documented MAME equations.

MAME 0.289 src/devices/sound/sn76477.cpp and nintendo/n8080_a.cpp.
Analog capacitor voltages use Q32 volts at 48 kHz, not guessed tone frequencies.
"""
from pathlib import Path
import math
import struct
ROOT = Path(__file__).resolve().parents[1]
Q = 1 << 32
RATE = 48000
def q(v): return round(v * Q)
def f32(v): return struct.unpack('<f',struct.pack('<f',v))[0]
constants = {
    'SLF_MIN': .33, 'SLF_MAX': 2.37, 'VCO_OFFSET': .35,
    'VCO_MAX': 2.72, 'VCO_5V_MAX': 5.35, 'NOISE_MAX': 5, 'NOISE_HIGH': 3.35,
    'NOISE_LOW': .74, 'AD_MAX': 4.44, 'SHOT_MAX': 2.5,
    'SLF_UP': 2.04 / (.5885 * 1.5e6 * 47e-9 + .001300) / RATE,
    'SLF_DOWN': 2.04 / (.5413 * 1.5e6 * 47e-9 + .001343) / RATE,
    'VCO_UP': .64 * 2 * 2.39 / (1.5e6 * 1e-9) / RATE,
    'VCO_UP_5V': .64 * 2 * 2.39 / (1.5e6 * 1e-9) / 1.64 / RATE,
    'VCO_DOWN_5V': .64 * 2 * 2.39 / (1.5e6 * 1e-9) * 1.64 / RATE,
    'NOISE_UP': 5 / (.1571 * 100e3 * 1e-9 + .00001430) / RATE,
    'NOISE_DOWN': 5 / (.1331 * 100e3 * 1e-9 + .00001734) / RATE,
    'AD_UP': 4.44 / (20e3 * 1e-6) / RATE,
    'AD_DOWN': 4.44 / (620e3 * 1e-6) / RATE,
    'SHOT_UP': 2.5 / (.8024 * 560e3 * 47e-9 + .002079) / RATE,
    'SHOT_DOWN': 2.5 / (854.7 * 47e-9 + .00001795) / RATE,
}
positive = [0]*9 + [.01,.03,.11,.15,.19,.21,.23,.26,.29,.31,.33,
    .36,.38,.41,.43,.46,.49,.52,.54,.57,.60,.62,.65,.68,.70,.73,.76,
    .80,.82,.84,.87,.90,.93,.96,.98,1]
negative = [0]*9 + [-.01,-.02,-.09,-.13,-.15,-.17,-.19,-.22,-.24,-.26,-.28,
    -.30,-.32,-.34,-.37,-.39,-.41,-.44,-.46,-.48,-.51,-.53,-.56,-.58,-.60,
    -.62,-.65,-.67,-.69,-.72,-.74,-.76,-.78,-.81,-.84,-.85]
text = '// Generated by tools/generate_sheriff_sn.py; Q32 volts, 48 kHz.\n'
for name, value in constants.items():
    text += f'localparam [35:0] {name} = 36\'d{q(value)}; // {value:.12g} V\n'
text += f'localparam integer NOISE_HZ = {int(339100000 * math.pow(36000, -.8849))};\n'
text += 'function automatic signed [15:0] gain_sample(input [5:0] index, input polarity);\n'
text += '    begin case ({polarity,index})\n'
for polarity, gains in enumerate([negative, positive]):
    for index, gain in enumerate(gains):
        # Preserve MAME's device normalization, float stream/route rounding,
        # and final truncation. No fitted amplitude or waveform offset.
        voltage = min(3.51, max(.715, 2.57 + (3.818 * (47e3 / 150e3) + .03) * gain))
        normalized = f32((voltage - .715) / (2.57 - .715) - 1)
        sample = int(f32(normalized * f32(.35)) * 32768)
        text += f'        7\'d{(polarity<<6)|index}: gain_sample = {"-" if sample<0 else ""}16\'sd{abs(sample)};\n'
text += "        default: gain_sample = 16'sd0;\n    endcase end\nendfunction\n"
(ROOT/'rtl/sheriff_sn_constants.svh').write_text(text)
print('Generated Sheriff SN76477 constants and 90 measured gain values')
