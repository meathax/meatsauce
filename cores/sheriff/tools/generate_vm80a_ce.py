"""Generate a pause-capable adaptation of the pinned, pristine vm80a kernel."""
import hashlib
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'rtl/vendor/vm80a/vm80a.v'
raw=source.read_bytes().replace(b'\r\n',b'\n')
expected='46e4e1def4768ddfa92b5585a0f90b92a77ab55219db42213165af0b7dad807f'
if hashlib.sha256(raw).hexdigest()!=expected:
    raise SystemExit('Pinned donor hash changed; inspect before regenerating adaptation')
text=raw.decode().replace('\r\n','\n')
core=text[text.index('module vm80a_core'):]
core=core.replace('module vm80a_core','module vm80a_core_ce',1)
core=core.replace('   input          pin_clk,','   input          pin_ce,        // freeze all sequential state when low\n   input          pin_clk,',1)
core,count=re.subn(r'always\s*@\s*\(posedge clk\)',r'always @(posedge clk)\nif (pin_ce)',core)
if count!=16:raise SystemExit(f'Expected 16 synchronous blocks, found {count}')
async_prefix='''always @(posedge clk or posedge reset)
begin
   if (reset)
      begin
         inta <= 0;
         inte <= 0;
      end
   else
'''
if core.count(async_prefix)!=1:raise SystemExit('Unexpected asynchronous reset block')
core=core.replace(async_prefix,async_prefix.rstrip()+' if (pin_ce)\n',1)
header=f'''// Derived from vm80a_core, Copyright (c) 2014-2018 by 1801BM1@gmail.com.
// Licensed under CC-BY 3.0 (https://creativecommons.org/licenses/by/3.0/).
// Nintendo 8080 project adaptation: a common sequential clock enable only.
// Generated by tools/generate_vm80a_ce.py; pristine donor SHA256 (LF): {expected}
// Keep original rtl/vendor/vm80a/vm80a.v and its attribution/provenance.
'''
target=ROOT/'rtl/n8080_vm80a_ce.v'
target.write_text(header+core,encoding='utf-8',newline='\n')
print(f'Generated {target}: 16 synchronous enables + asynchronous-reset else enable')
